# shellcheck shell=bash
# The firewall, seen from the PC: writes the lists for one container, applies
# them (plumbing/lock/apply.sh, privileged), tests them (plumbing/lock/test.sh, as
# dev). See plumbing/lock/ for what happens inside the container.

FILTER_PORT=3128

# Prints the domains of a sites file: no comments, no blank lines, lowercase.
read_sites() {
  [[ -f "$1" ]] || return 0
  sed -e 's/#.*//' -e 's/[[:space:]]//g' "$1" | tr '[:upper:]' '[:lower:]' | grep -v '^$' || true
}

# lock_write <project> <identity or "">
# Writes local/lock/<project>/: allowed.txt, filter, private.txt, ports.txt,
# tinyproxy.conf. Sources: plumbing/sites.txt (what the plumbing needs),
# config/sites.txt, config/projects/<project>/sites.txt, the identity's hosts.
lock_write() {
  local project=$1 identity=$2
  local dir="$MB_LOCAL/lock/$project"
  local plumb="$MB_PLUMBING/sites.txt" global="$MB_CONFIG/sites.txt" own="$MB_CONFIG/projects/$project/sites.txt"
  local hosts="" d f
  [[ -n "$identity" ]] && hosts="$MB_CONFIG/identities/$identity/hosts.txt"

  local -a domains=() private=() ports=(80 443)
  for f in "$plumb" "$global" "$own"; do
    while read -r d; do
      valid_domain "$d" || die "not a valid domain in $f: '$d'"
      domains+=("$d")
    done < <(read_sites "$f")
  done

  if [[ -n "$hosts" && -f "$hosts" ]]; then
    local url host port addr where
    while read -r url host port addr where _; do
      [[ -z "${url:-}" || "$url" == \#* ]] && continue
      domains+=("$host")
      ports+=("$port")
      [[ "$where" == private ]] && private+=("$addr $port")
    done < "$hosts"
  fi

  if (( MB_DRY )); then say "would write: $dir/{allowed.txt,filter,private.txt,ports.txt,tinyproxy.conf}"; return 0; fi

  mkdir -p "$dir"
  chmod 0755 "$dir"   # the filter runs as another user ("gate") and must read it
  local stamp; stamp="# Written by mirabelle on $(date '+%Y-%m-%d %H:%M:%S'). Do not edit: regenerated by run and lock."
  {
    say "$stamp"
    local from="plumbing/sites.txt, config/sites.txt"
    [[ -f "$own" ]] && from+=", config/projects/$project/sites.txt"
    [[ -n "$identity" ]] && from+=", hosts of identity $identity"
    say "# From: $from"
    printf '%s\n' "${domains[@]}" | sort -u
  } > "$dir/allowed.txt"
  printf '%s\n' "${domains[@]}" | sort -u | sed -e 's/\./\\./g' -e 's/^/(^|\\.)/' -e 's/$/$/' > "$dir/filter"
  { say "$stamp"; say "# address port, on the local network, that the filter may reach"; printf '%s\n' "${private[@]}"; } \
    | grep -v '^$' > "$dir/private.txt"
  printf '%s\n' "${ports[@]}" | sort -un > "$dir/ports.txt"
  {
    say "$stamp"
    say "Port $FILTER_PORT"
    say "Listen 127.0.0.1"
    say "Allow 127.0.0.1"
    say "Timeout 600"
    say "MaxClients 100"
    say "LogLevel Connect"
    say "DisableViaHeader Yes"
    say "FilterType ere"
    say "Filter \"/lock-run/filter\""
    say "FilterDefaultDeny Yes"
    say "FilterURLs Off"
    local p
    while read -r p; do [[ "$p" != 80 ]] && say "ConnectPort $p"; done < "$dir/ports.txt"
  } > "$dir/tinyproxy.conf"
  chmod 0644 "$dir"/*
}

# lock_apply <container>: kernel rules + filter (privileged), then the test
# (as dev). If anything fails, the container is removed.
lock_apply() {
  local c=$1
  if (( MB_DRY )); then
    printf 'would run: '; show_cmd docker exec -i -u root --privileged "$c" bash -s; say "           < $MB_PLUMBING/lock/apply.sh"
    printf 'would run: '; show_cmd docker exec -i -u dev "$c" bash -s; say "           < $MB_PLUMBING/lock/test.sh"
    return 0
  fi
  if ! query docker exec -i -u root --privileged "$c" bash -s < "$MB_PLUMBING/lock/apply.sh"; then
    run docker rm -f "$c" >/dev/null
    die "the firewall could not be set; container $c removed"
  fi
  if ! query docker exec -i -u dev "$c" bash -s < "$MB_PLUMBING/lock/test.sh"; then
    run docker rm -f "$c" >/dev/null
    die "the firewall test failed; container $c removed"
  fi
}

# Adds the proxy settings every container gets, to the array named $1.
add_proxy_env() {
  local -n _a=$1
  local p="http://127.0.0.1:$FILTER_PORT"
  _a+=(-e "HTTPS_PROXY=$p" -e "https_proxy=$p" -e "HTTP_PROXY=$p" -e "http_proxy=$p"
       -e "NO_PROXY=localhost,127.0.0.1" -e "no_proxy=localhost,127.0.0.1")
}

# Adds container settings shared by every mirabelle container.
add_base_opts() {
  local -n _b=$1
  _b+=(--init --cap-drop ALL --security-opt no-new-privileges)
  # IPv6 is turned off where the PC's kernel has it (the firewall covers IPv4).
  [[ -d /proc/sys/net/ipv6 ]] && _b+=(--sysctl net.ipv6.conf.all.disable_ipv6=1)
  return 0
}
